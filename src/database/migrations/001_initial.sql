CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  description text NOT NULL DEFAULT '',
  location varchar(160) NOT NULL,
  is_demo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE zones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name varchar(160) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned','stripping','stored','restoring','restored')),
  topsoil_depth_cm double precision NOT NULL CHECK (topsoil_depth_cm > 0 AND topsoil_depth_cm <= 300),
  geom geometry(Polygon,4326) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id, project_id),
  CHECK (ST_IsValid(geom) AND NOT ST_IsEmpty(geom)),
  CHECK (ST_Area(geom::geography) > 0 AND ST_Area(geom::geography) <= 1e10)
);

CREATE INDEX zones_project_idx ON zones(project_id);
CREATE INDEX zones_geom_idx ON zones USING gist(geom);

CREATE TABLE soil_measurements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id integer NOT NULL REFERENCES zones(id) ON DELETE CASCADE,
  moisture double precision NOT NULL CHECK (moisture BETWEEN 0 AND 100),
  temperature double precision NOT NULL CHECK (temperature BETWEEN -60 AND 80),
  ph double precision NOT NULL CHECK (ph BETWEEN 0 AND 14),
  measured_at timestamptz NOT NULL,
  source varchar(120) NOT NULL CHECK (length(trim(source)) > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX measurements_zone_date_idx ON soil_measurements(zone_id, measured_at DESC, id DESC);

CREATE TABLE activities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  zone_id integer NOT NULL,
  type varchar(20) NOT NULL CHECK (type IN ('stripping','movement','storage','reuse','restoration')),
  status varchar(20) NOT NULL CHECK (status IN ('planned','in_progress','completed')),
  occurred_at timestamptz NOT NULL,
  planned_volume_m3 double precision CHECK (planned_volume_m3 >= 0 AND planned_volume_m3 <= 1e10),
  actual_volume_m3 double precision CHECK (actual_volume_m3 >= 0 AND actual_volume_m3 <= 1e10),
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (zone_id, project_id) REFERENCES zones(id, project_id) ON DELETE CASCADE
);

CREATE INDEX activities_project_date_idx ON activities(project_id, occurred_at DESC);
CREATE INDEX activities_zone_idx ON activities(zone_id);
